/**
 * Don't Say The Same As Me: clock, durations, segments, parts, chapters.
 * Durations in seconds are written ONLY here. Scenes read timing from this file and data from data.ts.
 * Pattern (idea only, nothing imported): the clip-timing part of the earlier videos' timing.ts.
 */
import { useCurrentFrame } from 'remotion';
import { bonuses, heartCheckIn, levelColors, rounds } from './data';
import type { Bonus, Level, Round } from './data';
import { bonusAudio, bonusAudioOf, checkInId, hookIds, levelIds, outroIds, rankIds, rankIntroId, roundAudio, roundAudioOf } from './audioMap';
import { clipTimings } from './timings.generated';

/* ---------- clock ----------
 * Output is 2560x1440 at 60 fps. Scenes are authored in 30 fps "design frames" (ticks);
 * TIME_SCALE turns ticks into render frames. All `from` / `to` below are ticks, `to` exclusive. */
export const WIDTH = 2560;
export const HEIGHT = 1440;
export const RENDER_FPS = 60;
export const FPS = 30;
export const TIME_SCALE = RENDER_FPS / FPS;

/* ---------- durations in seconds: the only place they are written ---------- */
export const hookSec = 8;
export const introStdSec = 1.2;
export const introHeavySec = 3.2;
/** Round 45 only (the callback round). */
export const introCallbackSec = 4.2;
export const timerL1L2Sec = 5;
export const timerL3Sec = 4;
export const timerL4L5Sec = 3;
export const sealedSlideSec = 1.5;
/** Silence before the reveal. */
export const beatSec = 0.5;
export const revealSec = 2.0;
export const resultSec = 1.8;
export const levelCardSec = 4;
export const settingsCardSec = 4;
export const heartCheckInSec = 2;
/** Bonus split: 2 intro, 8 play, 3 reveal, 3 result = 16 s. */
export const bonusIntroSec = 2;
export const bonusPlaySec = 8;
export const bonusRevealSec = 3;
export const bonusResultSec = 3;
export const bonusSec = bonusIntroSec + bonusPlaySec + bonusRevealSec + bonusResultSec;
/** Rank card holds this long. */
export const rankCardSec = 6;
export const scoreboardSec = 20;
export const outroSec = 30;
/** The end screen is the last part of the outro. */
export const endScreenSec = 15;
/** Final fade to black at the very end of the outro. */
export const outroFadeSec = 1;
/** Slot padding after a voice clip, in seconds. */
export const clipPadSec = 0.3;
/** Silence between two voice lines that play back to back in one slot (round intro + rule, hook, rank card, outro). */
export const voiceGapSec = 0.25;
/** Target runtime ~10:44. The tolerance is a working assumption, not from the brief. */
export const targetSec = 10 * 60 + 44;
export const targetToleranceSec = 30;

/* ---------- frame helpers ---------- */
export const secToTicks = (sec: number): number => Math.round(sec * FPS);
export const ticksToSec = (ticks: number): number => ticks / FPS;
/** Design ticks -> render frames (60 fps). */
export const ticksToFrames = (ticks: number): number => Math.round(ticks * TIME_SCALE);
export const secToFrames = (sec: number): number => ticksToFrames(secToTicks(sec));
/** Current time in design ticks (fractional): scenes read this instead of useCurrentFrame. */
export const useDontSayFrame = (): number => useCurrentFrame() / TIME_SCALE;

/** "m:ss" for a time in seconds. */
export const timecode = (sec: number): string => {
  const s = Math.floor(sec + 1e-9);
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;
};

/* ---------- clip lengths ---------- */
const durOf = new Map(clipTimings.map((c) => [c.id, c.durSec] as const));
const fileOf = new Map(clipTimings.map((c) => [c.id, c.file] as const));
/** Length in seconds of a measured clip; undefined while timings do not exist (fallback = base value). */
export const clipSec = (id: string | undefined): number | undefined => (id ? durOf.get(id) : undefined);
/** `staticFile` path of a clip. */
export const clipPath = (id: string): string => `dontsay/voiceover/clips/${fileOf.get(id) ?? `${id}.wav`}`;

/** Clip ids are the ds_NNN ids of docs/dontsay/lines.csv, linked to rounds and bonuses by audioMap.ts
 *  (generated by scripts/build_dontsay_audio_map.ts); measured lengths come from timings.generated.ts. */
export type ClipKind = 'intro' | 'reveal' | 'result';
export type BonusClipKind = 'intro' | 'reveal';
export const roundClipId = (n: number, kind: ClipKind): string => {
  const id = roundAudioOf(n)[kind];
  if (!id) throw new Error(`timing: round ${n} has no ${kind} clip in audioMap.ts`);
  return id;
};
/** The rule clip of a heavy round (undefined for the other rounds). */
export const ruleClipId = (n: number): string | undefined => roundAudioOf(n).rule;
export const bonusClipId = (n: number, kind: BonusClipKind): string => bonusAudioOf(n)[kind];
/** Lookup for the slot rules below: a round missing from audioMap.ts keeps its base length instead of failing. */
const slotClipSec = (n: number, kind: 'intro' | 'reveal'): number | undefined => clipSec(roundAudio.find((a) => a.n === n)?.[kind]);

/* ---------- per-round rules ---------- */
export const timerSecFor = (level: Level): number => (level <= 2 ? timerL1L2Sec : level === 3 ? timerL3Sec : timerL4L5Sec);
/** Base intro length by round kind (callback first: round 45 is also heavy). */
export const introBaseSec = (r: Round): number => (r.callback ? introCallbackSec : r.heavy ? introHeavySec : introStdSec);
/** Slot rule for every voiced slot: max(base, clips back to back + voiceGapSec between them + pad). A missing clip keeps the base length. */
const fitSec = (base: number, ids: (string | undefined)[]): number => {
  const have = ids.filter((i): i is string => !!i);
  const lens = have.map((i) => clipSec(i));
  if (!lens.length || lens.some((l) => l === undefined)) return base;
  return Math.max(base, (lens as number[]).reduce((a, b) => a + b, 0) + voiceGapSec * (have.length - 1) + clipPadSec);
};
/** Intro slot = max(base, intro clip + rule clip (heavy rounds) + pad). */
export const introSecFor = (r: Round): number => {
  const a = roundAudio.find((x) => x.n === r.n);
  return fitSec(introBaseSec(r), [a?.intro, a?.rule]);
};
/** Reveal slot = max(revealSec, reveal clip + pad). */
export const revealSecFor = (r: Round): number => fitSec(revealSec, [roundAudio.find((a) => a.n === r.n)?.reveal]);
/** Result slot = max(resultSec, result clip + pad). */
export const resultSecFor = (r: Round): number => fitSec(resultSec, [roundAudio.find((a) => a.n === r.n)?.result]);
/** Level card = max(levelCardSec, level clip + pad). */
export const levelCardSecFor = (level: Level): number => fitSec(levelCardSec, [levelIds[level]?.level]);
/** Settings card (the rules sheet before level 1) = max(settingsCardSec, settings clip + pad). */
export const settingsCardSecFor = (): number => fitSec(settingsCardSec, [levelIds[1]?.settings]);
/** Heart check-in = max(heartCheckInSec, check-in clip + pad). */
export const checkInSecFor = (): number => fitSec(heartCheckInSec, [checkInId]);
/** Hook = max(hookSec, its clips with gaps + pad). */
export const hookSecFor = (): number => fitSec(hookSec, hookIds);
/** Rank card = max(rankCardSec, intro line + the five rank lines with gaps + pad). The scoreboard stays fixed. */
export const rankCardSecFor = (): number => fitSec(rankCardSec, [rankIntroId, ...rankIds]);
/** Outro = max(outroSec, its three clips with gaps + pad). The end screen stays the last endScreenSec. */
export const outroSecFor = (): number => fitSec(outroSec, outroIds);
/** Bonus phases: intro and reveal stretch to their clips; play and result stay fixed. */
export const bonusPhaseSecs = (n: number): { intro: number; play: number; reveal: number; result: number; total: number } => {
  const a = bonusAudio.find((x) => x.n === n);
  const intro = fitSec(bonusIntroSec, [a?.intro]);
  const reveal = fitSec(bonusRevealSec, [a?.reveal]);
  return { intro, play: bonusPlaySec, reveal, result: bonusResultSec, total: intro + bonusPlaySec + reveal + bonusResultSec };
};
export const bonusSecFor = (n: number): number => bonusPhaseSecs(n).total;
/** Phase boundaries of a bonus in design ticks, local to its start. */
export const bonusTicksFor = (n: number) => {
  const p = bonusPhaseSecs(n);
  const intro = secToTicks(p.intro);
  const play = intro + secToTicks(p.play);
  const reveal = play + secToTicks(p.reveal);
  const result = reveal + secToTicks(p.result);
  return { intro, play, reveal, result, chipAt: Math.round(intro / 2) } as const;
};

/* ---------- segments ---------- */
export type Range = { from: number; to: number };
export type PartNo = 1 | 2 | 3 | 4 | 5 | 6;
export type RoundPhases = { intro: Range; timer: Range; sealed: Range; beat: Range; reveal: Range; result: Range };
export type BonusPhases = { intro: Range; play: Range; reveal: Range; result: Range };

type Base = Range & { part: PartNo };
export type Segment =
  | ({ kind: 'hook' } & Base)
  | ({ kind: 'settingsCard' } & Base)
  | ({ kind: 'levelCard'; level: Level } & Base)
  | ({
      kind: 'round';
      round: Round;
      phases: RoundPhases;
      /** The small sealed ink bubble is on screen from the first tick of the round. */
      sealedFrom: number;
      /** Lock click ticks: the first tick of the round and the first tick of the reveal. */
      lockClickTicks: [number, number];
    } & Base)
  | ({ kind: 'heartCheckIn'; afterRound: number; beforeRound: number } & Base)
  | ({ kind: 'bonus'; bonus: Bonus; phases: BonusPhases } & Base)
  | ({ kind: 'rankCard' } & Base)
  | ({ kind: 'scoreboard' } & Base)
  | ({ kind: 'outro'; endScreen: Range } & Base);

const buildSegments = (): Segment[] => {
  const out: Segment[] = [];
  let cur = 0;
  const span = (sec: number): Range => {
    const r = { from: cur, to: cur + secToTicks(sec) };
    cur = r.to;
    return r;
  };
  let part: PartNo = 1;

  out.push({ kind: 'hook', part, ...span(hookSecFor()) });
  out.push({ kind: 'settingsCard', part, ...span(settingsCardSecFor()) });

  let lastLevel: Level | undefined;
  rounds.forEach((r) => {
    if (r.level !== lastLevel) {
      if (r.level > 1) part = r.level as PartNo;
      out.push({ kind: 'levelCard', level: r.level, part, ...span(levelCardSecFor(r.level)) });
      lastLevel = r.level;
    }
    const from = cur;
    const phases: RoundPhases = {
      intro: span(introSecFor(r)),
      timer: span(timerSecFor(r.level)),
      sealed: span(sealedSlideSec),
      beat: span(beatSec),
      reveal: span(revealSecFor(r)),
      result: span(resultSecFor(r)),
    };
    out.push({ kind: 'round', round: r, phases, sealedFrom: from, lockClickTicks: [from, phases.reveal.from], part, from, to: cur });

    if (r.n === heartCheckIn.afterRound) {
      out.push({ kind: 'heartCheckIn', afterRound: heartCheckIn.afterRound, beforeRound: heartCheckIn.beforeRound, part, ...span(checkInSecFor()) });
    }
    const b = bonuses.find((x) => x.afterRound === r.n);
    if (b) {
      const bFrom = cur;
      const ps = bonusPhaseSecs(b.n);
      const bp: BonusPhases = { intro: span(ps.intro), play: span(ps.play), reveal: span(ps.reveal), result: span(ps.result) };
      out.push({ kind: 'bonus', bonus: b, phases: bp, part, from: bFrom, to: cur });
    }
  });

  part = 6;
  out.push({ kind: 'rankCard', part, ...span(rankCardSecFor()) });
  out.push({ kind: 'scoreboard', part, ...span(scoreboardSec) });
  const o = span(outroSecFor());
  out.push({ kind: 'outro', part, ...o, endScreen: { from: o.to - secToTicks(endScreenSec), to: o.to } });
  return out;
};

export const segments: Segment[] = buildSegments();
export const TOTAL_TICKS = segments[segments.length - 1].to;
export const TOTAL_SEC = ticksToSec(TOTAL_TICKS);
/** Composition length at the render rate. */
export const RENDER_TOTAL_FRAMES = ticksToFrames(TOTAL_TICKS);

/* ---------- voice cues: the ONLY source of when a clip starts ---------- */
export type VoiceCue = { id: string; tick: number };
const need = (id: string | undefined, what: string): string => {
  if (!id) throw new Error(`voiceCues: ${what} has no clip id in audioMap.ts`);
  return id;
};
/** Clips one after another: each starts voiceGapSec after the previous one ends. Ticks local to the segment. */
const sequential = (ids: string[], startTick = 0): VoiceCue[] => {
  let tick = startTick;
  return ids.map((id) => {
    const cue = { id, tick };
    tick += secToTicks((clipSec(id) ?? 0) + voiceGapSec);
    return cue;
  });
};
/** Clips of one segment with the tick each one starts, local to the segment start. Ids come only from audioMap.ts. */
export const voiceCues = (seg: Segment): VoiceCue[] => {
  switch (seg.kind) {
    case 'round': {
      const a = roundAudioOf(seg.round.n);
      const out: VoiceCue[] = [{ id: need(a.intro, `round ${seg.round.n} intro`), tick: seg.phases.intro.from - seg.from }];
      if (seg.round.heavy) out.push({ id: need(a.rule, `round ${seg.round.n} rule`), tick: out[0].tick + secToTicks((clipSec(a.intro) ?? 0) + voiceGapSec) });
      out.push({ id: need(a.reveal, `round ${seg.round.n} reveal`), tick: seg.phases.reveal.from - seg.from });
      out.push({ id: need(a.result, `round ${seg.round.n} result`), tick: seg.phases.result.from - seg.from });
      return out;
    }
    case 'levelCard':
      return [{ id: need(levelIds[seg.level]?.level, `level ${seg.level} card`), tick: 0 }];
    case 'settingsCard':
      return [{ id: need(levelIds[1]?.settings, 'settings card'), tick: 0 }];
    case 'heartCheckIn':
      return [{ id: need(checkInId, 'heart check-in'), tick: 0 }];
    case 'bonus': {
      const a = bonusAudioOf(seg.bonus.n);
      return [
        { id: need(a.intro, `bonus ${seg.bonus.n} intro`), tick: 0 },
        { id: need(a.reveal, `bonus ${seg.bonus.n} reveal`), tick: seg.phases.reveal.from - seg.from },
      ];
    }
    case 'hook':
      return sequential(hookIds);
    case 'rankCard':
      return sequential([rankIntroId, ...rankIds]);
    case 'outro':
      return sequential(outroIds);
    case 'scoreboard':
      return [];
  }
};

/** The segment on screen at design tick `tick`, with the tick local to it. */
export const locate = (tick: number): { seg: Segment; local: number; index: number } => {
  for (let i = segments.length - 1; i >= 0; i--) if (tick >= segments[i].from) return { seg: segments[i], local: tick - segments[i].from, index: i };
  return { seg: segments[0], local: 0, index: 0 };
};
/** Render-frame range of a segment or phase. */
export const frameRange = (r: Range): { from: number; to: number; frames: number } => {
  const from = ticksToFrames(r.from);
  const to = ticksToFrames(r.to);
  return { from, to, frames: to - from };
};

/* ---------- parts ---------- */
export type PartRange = Range & { name: string; part: PartNo; ticks: number; renderFrom: number; renderTo: number; frames: number };

export const partLabels: Record<PartNo, string> = {
  1: 'Hook + Level 1 + Bonus 1',
  2: 'Level 2 + Bonus 2',
  3: 'Level 3 + check-in + Bonus 3',
  4: 'Level 4 + Bonus 4',
  5: 'Level 5 + callback + Bonus 5',
  6: 'Rank card + scoreboard + outro',
};

const partRange = (part: PartNo): PartRange => {
  const segs = segments.filter((s) => s.part === part);
  const from = segs[0].from;
  const to = segs[segs.length - 1].to;
  const renderFrom = ticksToFrames(from);
  const renderTo = ticksToFrames(to);
  return { name: `Part${part}`, part, from, to, ticks: to - from, renderFrom, renderTo, frames: renderTo - renderFrom };
};
export const partRanges: PartRange[] = ([1, 2, 3, 4, 5, 6] as PartNo[]).map(partRange);

/* ---------- chapters ---------- */
const titleCase = (s: string): string => s.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join(' ');
/** YouTube chapter lines, "m:ss Title". Chapters are in segment order. */
export const chapters: string[] = (() => {
  const at = (s: Segment): string => timecode(ticksToSec(s.from));
  const lines: string[] = [];
  segments.forEach((s) => {
    if (s.kind === 'hook') lines.push(`${at(s)} Intro`);
    else if (s.kind === 'levelCard') lines.push(`${at(s)} Level ${s.level}: ${levelColors[s.level].name}`);
    else if (s.kind === 'bonus') lines.push(`${at(s)} Bonus ${s.bonus.n}: ${titleCase(s.bonus.name)}`);
    else if (s.kind === 'rankCard') lines.push(`${at(s)} Your rank`);
    else if (s.kind === 'outro') lines.push(`${at(s)} Outro`);
  });
  return lines;
})();
