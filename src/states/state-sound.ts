/**
 * state-sound.ts (task 6b): the audio plan of Video 4. Adapted from src/sound.ts: pure arithmetic over
 * TIMELINE.segments, no DOM, so every frame is deterministic and any frame range renders in any order.
 *
 *   STATE_CUES              every scene's cue list at its segment offset (absolute design tick = 30 per second)
 *   STATE_VOICE             voiceover clips from states-voiceover-manifest.json at their segment offsets
 *   STATE_MUSIC_ENVELOPES   per-tick volume of the three music layers (music-base, music-l1, music-l2)
 *
 * Voiceover timing is NOT changed: clip positions are read from the scene plans / state-timing helpers
 * (hook HOOK_PLAN.vo, level card stateLevelCardVoice, question plan.vo, scoreboard scoreboardVoicePlan,
 * end screen endScreenVoice) and the bonus clips follow the word quiz: the question clip (bonusq) starts
 * `voiceover.offsetFrames` into the segment, the answer clip (bonus) `offsetFrames` after the clock ends.
 *
 * Cue bases: question cues count from plan tick 0 = seg.from - seg.lead (as stateRoundCues says); all other
 * scenes count from seg.from.
 *
 * MUSIC BEDS PER LEVEL (4 levels, 3 loops): the layers are stacked by level, the third layer comes in
 * quieter for HARD so EXPERT is the first time everything plays at full volume.
 *     level index   base   l1    l2
 *     0 EASY        1      0     0
 *     1 MEDIUM      1      1     0
 *     2 HARD        1      1     0.6
 *     3 EXPERT      1      1     1
 * (LEVEL_BED, by index in states-settings.json levels; a longer list reuses the last row.) The hook plays the
 * base bed; a level card, its questions and the wipes between them play their level's bed, a bonus plays all
 * three at full volume (like the word quiz), the wipe after a bonus keeps the bonus bed until the next level
 * card / question sets its own. Layers fade over RAMP ticks. The music stops at the scoreboard, as in the
 * word quiz (MUSIC_END).
 *
 * EXTRAS: a short stinger on every level card (`chime-arp`, pitched up one step per level); a `riser` on the last
 * second of every clock (questions and bonuses), during which the music is hushed (root settings sound.panic
 * hushFloor / hushRamp) until the clock ends; a `boom` with the answer stamp (sound.panic.stampBoomVolume).
 * Ducking: every cue dips the music to DUCK_FLOOR for a moment, every voiceover clip to voiceover.duckFloor.
 * Nothing here has been listened to.
 */
import root from '../../settings.json';
import soundManifest from '../sound-manifest.json';
import settings from './states-settings.json';
import {
  BONUS_CLOCK_START,
  BONUS_PUZZLES,
  FPS,
  LEVELS,
  TIMELINE,
  bonusClockFrames,
  buildQuestionPlan,
  voiceBonus,
  voiceBonusQuestion,
} from './state-timing';
import { HOOK_PLAN, stateHookCues } from './scenes/StateHook';
import { stateLevelCardCues, stateLevelCardVoice, LEVEL_BEATS } from './scenes/StateLevelCard';
import { stateRoundCues } from './scenes/stateRoundCues';
import type { StateCue, StateSfx } from './scenes/stateRoundCues';
import { stateBonusCues } from './scenes/StateBonus';
import { stateReminderCues } from './scenes/StateReminder';
import { stateIrisCues } from './scenes/StateIris';
import { scoreboardVoicePlan, stateScoreboardCues } from './scenes/StateScoreboard';
import { endScreenVoice, stateEndScreenCues } from './scenes/StateEndScreen';

export const STATE_SOUND_ENABLED = Boolean((root as { sound?: { enabled?: boolean } }).sound?.enabled);

/** Music loop = exactly 256 ticks at 30 fps (the word quiz loops, generated by scripts/generate-audio.js). */
export const MUSIC_LOOP_FRAMES = 256;

export const VOICE_DIR = root.voiceover.dir;

/** Clip length in ticks (rounded up, +1 so a clip is never cut). */
export const clipFrames = (sfx: StateSfx, rate = 1) => Math.ceil((soundManifest[sfx] * FPS) / rate) + 1;

/**
 * Whether question `index` (0-based) plays with the title lockup: the first question and the question right after a
 * bonus (state-timing's buildTimeline: `withTitle` starts true and is set again after each bonus). StateRound and the
 * cue lists must use the same value the timeline used for buildQuestionPlan.
 */
export const questionHasTitle = (index: number): boolean => index === 0 || (settings.bonus.after as number[]).includes(index);

/** A voiceover clip placed on the timeline (absolute design tick, length in ticks). */
export type StateVoice = { frame: number; file: string; frames: number };

// ------------------------------------------------------------------ music bed per level
/** Layer gains [base, l1, l2] by level index. */
const LEVEL_BED: number[][] = [
  [1, 0, 0],
  [1, 1, 0],
  [1, 1, 0.6],
  [1, 1, 1],
];
const HOOK_BED = LEVEL_BED[0];
const BONUS_BED = [1, 1, 1];
const bedOf = (levelIndex: number): number[] => LEVEL_BED[Math.max(0, Math.min(LEVEL_BED.length - 1, levelIndex))];

/** Windows where the music drops (the silent beat of the last second of a clock). */
type Window = { from: number; to: number };

// ------------------------------------------------------------------ build the plan
const PANIC = root.sound.panic;

const build = () => {
  const cues: StateCue[] = [];
  const voice: StateVoice[] = [];
  const hushes: Window[] = [];
  const beds: { frame: number; gains: number[] }[] = [{ frame: 0, gains: HOOK_BED }];

  const addAt = (base: number, list: StateCue[]) => list.forEach((c) => cues.push({ ...c, frame: Math.round(base + c.frame) }));
  const add = (frame: number, sfx: StateSfx, extra: Partial<StateCue> = {}) => cues.push({ frame: Math.round(frame), sfx, ...extra });
  const voiceAt = (frame: number, clip: { file: string; frames: number } | undefined) => {
    if (clip) voice.push({ frame: Math.round(frame), file: clip.file, frames: clip.frames });
  };
  /** the riser fills the last second of a clock; the music hushes under it */
  const riser = (clockEnd: number) => {
    add(clockEnd - PANIC.riserFrames, 'riser');
    hushes.push({ from: clockEnd - PANIC.riserFrames, to: clockEnd });
  };

  TIMELINE.segments.forEach((seg) => {
    const f0 = seg.from;
    switch (seg.kind) {
      case 'hook': {
        addAt(f0, stateHookCues());
        voiceAt(f0 + (HOOK_PLAN.vo?.start ?? 0), HOOK_PLAN.vo);
        break;
      }
      case 'levelCard': {
        beds.push({ frame: f0, gains: bedOf(seg.levelIndex) });
        addAt(f0, stateLevelCardCues());
        // stinger, pitched up one step per level
        add(f0 + LEVEL_BEATS.nameAt, 'chime-arp', { rate: 1 + 0.12 * seg.levelIndex, volume: 0.8 });
        const v = stateLevelCardVoice(seg.levelIndex);
        if (v) voiceAt(f0 + v.frame, v);
        break;
      }
      case 'question': {
        const lead = seg.lead ?? 0;
        const base = f0 - lead;
        const plan = buildQuestionPlan(seg.index, questionHasTitle(seg.index));
        beds.push({ frame: f0, gains: bedOf(plan.levelIndex) });
        addAt(base, stateRoundCues(seg.index, questionHasTitle(seg.index)));
        riser(base + plan.timerStart + plan.timerFrames);
        add(base + plan.stamp, 'boom', { volume: PANIC.stampBoomVolume });
        if (plan.vo) voiceAt(base + plan.vo.start, plan.vo);
        break;
      }
      case 'bonus': {
        beds.push({ frame: f0, gains: BONUS_BED });
        const puzzle = BONUS_PUZZLES[seg.index];
        addAt(f0, stateBonusCues(puzzle));
        const clockEnd = BONUS_CLOCK_START + bonusClockFrames(seg.index);
        riser(f0 + clockEnd);
        // voiceover: question clip near the start, answer clip right after the clock (same placement as the word quiz)
        voiceAt(f0 + root.voiceover.offsetFrames, voiceBonusQuestion(seg.index + 1));
        voiceAt(f0 + clockEnd + root.voiceover.offsetFrames, voiceBonus(seg.index + 1));
        break;
      }
      case 'reminder':
        addAt(f0, stateReminderCues());
        break;
      case 'iris':
        addAt(f0, stateIrisCues(seg));
        break;
      case 'scoreboard': {
        addAt(f0, stateScoreboardCues());
        scoreboardVoicePlan().forEach((v) => voiceAt(f0 + v.start, v));
        break;
      }
      case 'endScreen': {
        addAt(f0, stateEndScreenCues());
        const v = endScreenVoice();
        if (v) voiceAt(f0 + v.start, v);
        break;
      }
    }
  });

  return {
    cues: cues.filter((c) => c.frame >= 0).sort((a, b) => a.frame - b.frame),
    voice: voice.sort((a, b) => a.frame - b.frame),
    hushes,
    beds,
  };
};

const PLAN = build();

export const STATE_CUES: StateCue[] = PLAN.cues;
/** Every voiceover clip in the video, in order. */
export const STATE_VOICE: StateVoice[] = PLAN.voice;

// ------------------------------------------------------------------ music
/** First tick with no music (the scoreboard, as in the word quiz). */
export const MUSIC_END = (TIMELINE.segments.find((s) => s.kind === 'scoreboard') ?? { from: TIMELINE.totalFrames }).from;

const RAMP = 10; // ticks for a layer to fade in / out
const DUCK_FLOOR = 0.44; // every sound dips the music to this

const buildEnvelopes = (): Float32Array[] => {
  const n = Math.max(1, TIMELINE.totalFrames);
  const duck = new Float32Array(n).fill(1);

  // every cue dips the music for a moment
  const duckFrames = FPS * 0.28;
  const recover = FPS * 0.18;
  for (const c of PLAN.cues) {
    for (let f = Math.max(0, c.frame); f < Math.min(n, c.frame + duckFrames + recover * 4); f++) {
      const dt = f - c.frame;
      const v = dt < duckFrames ? DUCK_FLOOR : 1 - (1 - DUCK_FLOOR) * Math.exp(-(dt - duckFrames) / recover);
      if (v < duck[f]) duck[f] = v;
    }
  }

  // hush windows (last second of a clock): ramp down just before, hold at the floor, snap back at the end
  for (const h of PLAN.hushes) {
    const ramp = PANIC.hushRamp;
    for (let f = Math.max(0, h.from - ramp); f < Math.min(n, h.to); f++) {
      const v = f < h.from ? 1 - (1 - PANIC.hushFloor) * ((f - (h.from - ramp) + 1) / (ramp + 1)) : PANIC.hushFloor;
      if (v < duck[f]) duck[f] = v;
    }
  }

  // the music dips under every voiceover clip: quick attack, slower release
  const vDuck = root.voiceover.duckFloor;
  for (const v of PLAN.voice) {
    const a = Math.max(0, v.frame - 4);
    const b = Math.min(n, v.frame + v.frames + 12);
    for (let f = a; f < b; f++) {
      const down = Math.min(1, (f - a) / 4);
      const up = Math.min(1, (v.frame + v.frames + 12 - f) / 12);
      const val = 1 - (1 - vDuck) * Math.min(down, up);
      if (val < duck[f]) duck[f] = val;
    }
  }

  return [0, 1, 2].map((layer) => {
    const env = new Float32Array(n);
    let bi = 0;
    let gain = PLAN.beds[0].gains[layer];
    let cur = layer === 0 ? gain : 0;
    for (let f = 0; f < n; f++) {
      while (bi < PLAN.beds.length && PLAN.beds[bi].frame <= f) gain = PLAN.beds[bi++].gains[layer];
      const target = f >= MUSIC_END ? 0 : gain;
      const step = 1 / RAMP;
      cur = cur < target ? Math.min(target, cur + step) : Math.max(target, cur - step);
      env[f] = cur * duck[f];
    }
    return env;
  });
};

export const STATE_MUSIC_ENVELOPES = buildEnvelopes();

/** Does `layer` make any sound inside [from, to)? Lets the soundtrack skip silent loop repeats. */
export const layerAudible = (layer: number, from: number, to: number) => {
  const env = STATE_MUSIC_ENVELOPES[layer];
  for (let f = Math.max(0, from); f < Math.min(env.length, to); f += 3) if (env[f] > 0.001) return true;
  return false;
};

