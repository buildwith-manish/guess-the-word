/**
 * Bakes the music ducking envelope of XMAS-Full from the voice clip timeline (src/xmas/voiceTimeline.ts), copies the
 * music licence text into the build, and prints the mix checks.
 * Run: npx tsx scripts/build_xmas_duck.ts      (re-run after any change to clips, timings, parts or docs/xmas/music-license.md)
 *
 * Writes
 *   src/xmas/duckEnvelope.generated.ts   keyframes [render frame, music gain multiplier 0..1], linear between keys.
 *                                        Gain is 1 with no voice and the duck gain while a clip plays; it ramps
 *                                        MIX.duckAttackSec before a clip and MIX.duckReleaseSec after it; clips closer
 *                                        than attack + release share one dip.
 *   src/xmas/musicLicense.generated.ts   the text between the marker lines of docs/xmas/music-license.md ('' = none yet)
 * Prints
 *   voice/voice overlaps, voice in thinking time, sounds other than ticks in movie thinking time, the gain of every
 *   sound effect, and every sound effect that starts with a voice clip or plays over one.
 * Clip lengths come from src/xmas/timings.csv (id,type,slot,part,durSec), the same file the timing build writes.
 * It changes no clip, text or timing.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import * as path from 'node:path';
import { MIX, musicDuckGain, sfxGainFor } from '../src/xmas/mix';
import { voiceEvents, voiceSignature, voiceStartFrame } from '../src/xmas/voiceTimeline';
import { part1Cues, part2Cues, part3Cues } from '../src/xmas/sfxCues';
import { sfxEntry } from '../src/xmas/sfx';
import { RENDER_FPS, RENDER_TOTAL_FRAMES, partRanges, segments, ticksToFrames, timecode } from '../src/xmas/timing';

const root = path.resolve(path.dirname(process.argv[1] ?? '.'), '..');
const csvPath = path.join(root, 'src', 'xmas', 'timings.csv');
const licensePath = path.join(root, 'docs', 'xmas', 'music-license.md');

const report: string[] = [];
const log = (line = ''): void => {
  console.log(line);
  report.push(line);
};

const fail = (msg: string): never => {
  console.error(`ERROR: ${msg}`);
  process.exit(1);
};

/* ---------- clip lengths ---------- */
const durOf = new Map<string, number>();
{
  const lines = readFileSync(csvPath, 'utf8').split(/\r?\n/).filter((l) => l.trim() !== '');
  const head = lines[0].split(',').map((h) => h.trim());
  const ci = head.indexOf('id');
  const di = head.indexOf('durSec');
  if (ci < 0 || di < 0) fail(`${csvPath}: needs columns id and durSec`);
  for (const l of lines.slice(1)) {
    const f = l.split(',').map((x) => x.trim());
    durOf.set(f[ci], Number(f[di]));
  }
}
const missing = voiceEvents.filter((e) => !Number.isFinite(durOf.get(e.id)));
if (missing.length) fail(`no clip length in timings.csv for: ${missing.map((e) => e.id).join(', ')}`);

type Span = { id: string; what: string; a: number; b: number };
const spans: Span[] = voiceEvents
  .map((e) => ({ id: e.id, what: e.what, a: voiceStartFrame(e), b: voiceStartFrame(e) + Math.ceil(durOf.get(e.id)! * RENDER_FPS) }))
  .sort((x, y) => x.a - y.a);

/* ---------- duck envelope ---------- */
const att = Math.round(MIX.duckAttackSec * RENDER_FPS);
const rel = Math.round(MIX.duckReleaseSec * RENDER_FPS);
const merged: [number, number][] = [];
for (const s of spans) {
  const last = merged[merged.length - 1];
  if (last && s.a - last[1] < att + rel) last[1] = Math.max(last[1], s.b);
  else merged.push([s.a, s.b]);
}
const keys: [number, number][] = [[0, 1]];
const push = (f: number, g: number) => {
  const prev = keys[keys.length - 1];
  keys.push([f <= prev[0] ? prev[0] + 1 : f, Math.round(g * 1000) / 1000]);
};
for (const [a, b] of merged) {
  push(Math.max(0, a - att), 1);
  push(a, musicDuckGain);
  push(b, musicDuckGain);
  push(b + rel, 1);
}
push(RENDER_TOTAL_FRAMES, 1);

const sig = voiceSignature();
const keyLines = keys.map((k) => `[${k[0]}, ${k[1]}]`);
const rows: string[] = [];
for (let i = 0; i < keyLines.length; i += 8) rows.push('  ' + keyLines.slice(i, i + 8).join(', ') + ',');
writeFileSync(
  path.join(root, 'src', 'xmas', 'duckEnvelope.generated.ts'),
  `/* Generated by scripts/build_xmas_duck.ts from src/xmas/voiceTimeline.ts and src/xmas/timings.csv. Do not edit. */
/** Fingerprint of the voice timeline this envelope was baked from (Audio.tsx throws when it no longer matches). */
export const DUCK_SIGNATURE = '${sig}';
/** [render frame of XMAS-Full, music gain multiplier 0..1], linear between keys. */
export const DUCK_KEYS: readonly (readonly [number, number])[] = [
${rows.join('\n')}
];
`,
);

/* ---------- music licence text ---------- */
{
  const md = readFileSync(licensePath, 'utf8');
  const m = /<!--\s*LICENSE-TEXT-START\s*-->([\s\S]*?)<!--\s*LICENSE-TEXT-END\s*-->/.exec(md);
  if (!m) fail(`${licensePath}: the LICENSE-TEXT-START and LICENSE-TEXT-END marker lines are missing`);
  const text = m![1].replace(/<!--[\s\S]*?-->/g, '').trim();
  writeFileSync(
    path.join(root, 'src', 'xmas', 'musicLicense.generated.ts'),
    `/* Generated by scripts/build_xmas_duck.ts from docs/xmas/music-license.md. Do not edit; paste the licence there and re-run the script. */
/** The licence text of the music bed; '' while none has been pasted. Audio.tsx refuses a build with music and no text. */
export const MUSIC_LICENSE_TEXT: string = ${JSON.stringify(text)};
`,
  );
  log(`music licence text: ${text ? `${text.length} characters copied` : 'EMPTY (a build with MUSIC_FILE set will be refused until it is pasted)'}`);
}

/* ---------- reports ---------- */
const tc = (frame: number): string => {
  const sec = frame / RENDER_FPS;
  return `${timecode(sec)}.${String(Math.floor((sec % 1) * 100)).padStart(2, '0')} (frame ${frame})`;
};
log(`\nvoice clips ${voiceEvents.length}, dips ${merged.length}, keys ${keys.length}, signature ${sig}`);
log(`music: duck ${MIX.musicDuckDb} dB, attack ${att} frames, release ${rel} frames`);

const overlaps = spans.flatMap((s, i) => (i > 0 && s.a < spans[i - 1].b ? [{ a: spans[i - 1], b: s, by: (spans[i - 1].b - s.a) / RENDER_FPS }] : []));
log(`\nvoice/voice overlaps: ${overlaps.length}`);
for (const o of overlaps) log(`  ${tc(o.b.a)}  ${o.a.id} (${o.a.what}) is still playing ${o.by.toFixed(2)} s when ${o.b.id} (${o.b.what}) starts`);

/* sound effects, absolute render frames */
type Sfx = { id: string; a: number; b: number };
const sfx: Sfx[] = [part1Cues, part2Cues, part3Cues]
  .flatMap((cues, i) =>
    cues.map((c) => {
      const a = ticksToFrames(c.frame + partRanges[i].from);
      return { id: c.sfx as string, a, b: a + Math.ceil((sfxEntry(c.sfx).length / (c.rate ?? 1)) * RENDER_FPS) };
    }),
  )
  .sort((x, y) => x.a - y.a);
log(`\nsound effects: ${sfx.length}`);

/* thinking time: only the music bed and the timer ticks */
const thinking = segments.flatMap((s) => (s.kind === 'slot' ? [{ slot: s.slot, a: ticksToFrames(s.phases.timer.from), b: ticksToFrames(s.phases.timer.to) }] : []));
const voiceInThinking = thinking.flatMap((t) => spans.filter((v) => v.a < t.b && v.b > t.a).map((v) => ({ t, v })));
log(`\nvoice clips inside thinking or playing time: ${voiceInThinking.length}`);
for (const x of voiceInThinking) log(`  slot ${x.t.slot.slot}: ${x.v.id} (${x.v.what}) ${tc(x.v.a)} to ${tc(x.v.b)}`);
const other = thinking.filter((t) => t.slot.kind === 'movie').flatMap((t) => sfx.filter((s) => s.a >= t.a && s.a < t.b && !s.id.startsWith('tick-')).map((s) => ({ t, s })));
log(`sounds other than timer ticks inside movie thinking time: ${other.length}`);
for (const x of other) log(`  slot ${x.t.slot.slot}: ${x.s.id} at ${tc(x.s.a)}`);

/* level of each sound effect */
log(`\nsound effect levels (plain RMS under the voice's about ${MIX.voiceRmsDb} dBFS; target ${MIX.sfxUnderVoiceDb} dB under):`);
for (const id of [...new Set(sfx.map((s) => s.id))].sort()) {
  const e = sfxEntry(id as Parameters<typeof sfxEntry>[0]);
  const g = sfxGainFor(e.rmsDb);
  log(`  ${id.padEnd(14)} file rms ${e.rmsDb.toFixed(1).padStart(6)} dB, gain ${(20 * Math.log10(g)).toFixed(1).padStart(6)} dB, ends at ${(e.rmsDb + 20 * Math.log10(g) - MIX.voiceRmsDb).toFixed(1)} dB vs voice`);
}

/* collisions with voice clips */
const START_WINDOW = 2; // frames: a sound that starts within this many frames of a clip start collides with it
const startHits = sfx.flatMap((s) => spans.filter((v) => Math.abs(s.a - v.a) <= START_WINDOW).map((v) => ({ s, v })));
log(`\nsound effect starts together with a voice clip (within ${START_WINDOW} frames): ${startHits.length}`);
for (const h of startHits) log(`  ${tc(h.v.a)}  ${h.s.id} at frame ${h.s.a} with ${h.v.id} (${h.v.what}), ${h.s.a - h.v.a >= 0 ? '+' : ''}${h.s.a - h.v.a} frames`);

const over = sfx.flatMap((s) => spans.filter((v) => s.a < v.b && s.b > v.a && Math.abs(s.a - v.a) > START_WINDOW).map((v) => ({ s, v })));
log(`\nsound effect plays over a voice clip, not starting with it: ${over.length}`);
const byKind = new Map<string, number[]>();
for (const o of over) {
  const k = `${o.s.id} over ${o.v.what.replace(/\d+/g, 'N')}`;
  byKind.set(k, [...(byKind.get(k) ?? []), o.s.a - o.v.a]);
}
for (const [k, offs] of [...byKind.entries()].sort()) {
  const lo = Math.min(...offs);
  const hi = Math.max(...offs);
  log(`  ${String(offs.length).padStart(3)} x ${k}, starts ${lo === hi ? `${lo}` : `${lo} to ${hi}`} frames ${lo < 0 ? 'relative to the clip start (negative = before it)' : 'after the clip starts'}`);
}
log('(the sound is 7 dB under the voice by the gains above; "over" is by design where the picture and the sound belong together.)');

const reportPath = path.join(root, 'docs', 'xmas', 'mix-report.txt');
writeFileSync(reportPath, `Generated by scripts/build_xmas_duck.ts. Do not edit.\n\n${report.join('\n')}\n`);
console.log(`\nreport saved to ${path.relative(root, reportPath)}`);
