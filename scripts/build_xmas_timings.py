#!/usr/bin/env python3
"""Measures every Christmas quiz voiceover clip with ffprobe and writes src/xmas/timings.csv plus
src/xmas/timings.generated.ts (the same rows as a typed module, because the Remotion bundle cannot read a CSV at
runtime; src/xmas/timing.ts reads `clipTimings` and falls back to its base constants for a slot without both clips).

Rows are walked in file order, the same order scripts/build_xmas_audio_map.ts checks: hook, then per slot an intro row
(quip or bonusintro) and a reveal row (reveal or bonusreveal), then end, rank and outro rows. The slot number is
counted from the intro rows, so no slot number is written by hand.

Run:   python3 scripts/build_xmas_timings.py     (re-run after any change to the clips, e.g. clean_xmas_clips.sh)
Env:   CSV=docs/xmas/lines.csv  CLIPS=public/xmas/voiceover/clips
Exit 1 if any id in lines.csv has no clip (nothing is written then). Clips with no row are only reported."""
import csv, json, os, subprocess, sys

CSV = os.environ.get('CSV', 'docs/xmas/lines.csv')
CLIPS = os.environ.get('CLIPS', 'public/xmas/voiceover/clips')
OUT_CSV = 'src/xmas/timings.csv'
OUT_TS = 'src/xmas/timings.generated.ts'
EXTS = ('.wav', '.mp3', '.m4a', '.flac', '.ogg')
INTRO_TYPES = ('quip', 'bonusintro')
REVEAL_TYPES = ('reveal', 'bonusreveal')

with open(CSV, newline='', encoding='utf-8') as f:
    rows = [(r['id'].strip(), r['type'].strip()) for r in csv.DictReader(f) if r.get('id', '').strip()]

files = {}
for name in os.listdir(CLIPS) if os.path.isdir(CLIPS) else []:
    base, ext = os.path.splitext(name)
    if ext.lower() in EXTS:
        files[base] = os.path.join(CLIPS, name)

missing = [i for i, _ in rows if i not in files]
if missing:
    print(f'FAIL: {len(missing)} id(s) in {CSV} have no clip in {CLIPS}: ' + ', '.join(missing), file=sys.stderr)
    sys.exit(1)
orphans = sorted(set(files) - {i for i, _ in rows})
if orphans:
    print('warning: clips with no row (ignored): ' + ', '.join(orphans), file=sys.stderr)

def duration(path):
    r = subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', path], capture_output=True, text=True)
    try:
        return round(float(r.stdout.strip()), 3)
    except ValueError:
        print(f'FAIL: ffprobe could not read {path}: {r.stderr.strip()}', file=sys.stderr)
        sys.exit(1)

lines, slots = [], []
slot = 0
for i, t in rows:
    d = duration(files[i])
    lines.append((i, t, d))
    if t in INTRO_TYPES:
        slot += 1
        slots.append((slot, 'intro', i, t, d))
    elif t in REVEAL_TYPES:
        if slot == 0:
            print(f'FAIL: {i} ({t}) comes before any intro row', file=sys.stderr)
            sys.exit(1)
        slots.append((slot, 'reveal', i, t, d))

with open(OUT_CSV, 'w', encoding='utf-8', newline='') as f:
    f.write('id,type,slot,part,durSec\n')
    part_of = {i: (s, p) for s, p, i, _, _ in slots}
    for i, t, d in lines:
        s, p = part_of.get(i, ('', ''))
        f.write(f'{i},{t},{s},{p},{d:.3f}\n')

with open(OUT_TS, 'w', encoding='utf-8') as f:
    f.write('/* Generated by scripts/build_xmas_timings.py from public/xmas/voiceover/clips. Do not edit.\n'
            ' * clipTimings: one entry per spoken intro or reveal of a slot (read by timing.ts). lineTimings: every row of lines.csv. */\n')
    f.write("export type ClipTiming = { slot: number; part: 'intro' | 'reveal'; durSec: number };\n\n")
    f.write('export const clipTimings: ClipTiming[] = [\n')
    for s, p, _, _, d in slots:
        f.write(f"  {{ slot: {s}, part: {json.dumps(p)}, durSec: {d} }},\n")
    f.write('];\n\n')
    f.write('export type LineTiming = { id: string; type: string; durSec: number };\n\n')
    f.write('export const lineTimings: LineTiming[] = [\n')
    for i, t, d in lines:
        f.write(f'  {{ id: {json.dumps(i)}, type: {json.dumps(t)}, durSec: {d} }},\n')
    f.write('];\n')

print(f'ok: {len(lines)} clips ({len(slots)} slot clips for {slot} slots), total {sum(d for _, _, d in lines):.1f} s -> {OUT_CSV}, {OUT_TS}')
