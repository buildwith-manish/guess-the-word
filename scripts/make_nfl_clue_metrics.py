#!/usr/bin/env python3
"""Writes src/nfl/components/clueMetrics.generated.ts: Inter 600 advance widths (font units / unitsPerEm) for ASCII
plus every other character used in docs/nfl/cards.json clues. ClueStack uses it to wrap and size clue text
deterministically (no DOM measuring, so it does not depend on the font having loaded).
Needs: pip install fonttools brotli.  Run: python3 scripts/make_nfl_clue_metrics.py"""
import json
from fontTools.ttLib import TTFont

font = TTFont('public/fonts/ios/Inter-600.woff2')
cmap, hmtx, upm = font.getBestCmap(), font['hmtx'], font['head'].unitsPerEm
cards = json.load(open('docs/nfl/cards.json'))['cards']
chars = set(chr(c) for c in range(32, 127)) | set(ch for c in cards for t in c['clues'] for ch in t)
missing = sorted(ch for ch in chars if ord(ch) not in cmap)
widths = {ch: round(hmtx[cmap[ord(ch)]][0] / upm, 4) for ch in sorted(chars) if ord(ch) in cmap}
lines = ['// Generated by scripts/make_nfl_clue_metrics.py. Do not edit.',
         '// Inter 600 advance widths in em (1 = font size).',
         'export const INTER_600_EM: Record<string, number> = {']
lines += [f'  {json.dumps(ch)}: {w},' for ch, w in widths.items()]
lines += ['};', f'/** Characters the font has no glyph for (measured with the fallback width). */',
          f'export const INTER_600_MISSING: string[] = {json.dumps(missing)};', '']
open('src/nfl/components/clueMetrics.generated.ts', 'w').write('\n'.join(lines))
print(len(widths), 'chars; missing:', missing)
