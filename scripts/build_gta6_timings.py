#!/usr/bin/env python3
"""Measures every GTA 6 voiceover clip with ffprobe and writes src/gta6/timings.csv (id,type,durSec)
plus src/gta6/timings.generated.ts (the same rows as a typed module, because the Remotion bundle cannot read a
CSV file at runtime; src/gta6/timing.ts imports the .ts file and falls back to its constants when it is empty).

Run:   python3 scripts/build_gta6_timings.py            (re-run after any change to the clips, e.g. clean_gta6_clips.sh)
Env:   CSV=docs/gta6/lines.csv  CLIPS=public/gta6/voiceover/clips
Exit 1 if any id in lines.csv has no clip (nothing is written then). Clips with no row are only reported."""
import csv, json, os, subprocess, sys

CSV = os.environ.get('CSV', 'docs/gta6/lines.csv')
CLIPS = os.environ.get('CLIPS', 'public/gta6/voiceover/clips')
OUT_CSV = 'src/gta6/timings.csv'
OUT_TS = 'src/gta6/timings.generated.ts'
EXTS = ('.wav', '.mp3', '.m4a', '.flac', '.ogg')

with open(CSV, newline='', encoding='utf-8') as f:
    rows = [(r['id'].strip(), r['type'].strip()) for r in csv.DictReader(f) if r.get('id', '').strip()]

files = {}
for name in os.listdir(CLIPS) if os.path.isdir(CLIPS) else []:
    base, ext = os.path.splitext(name)
    if ext.lower() in EXTS:
        files[base] = os.path.join(CLIPS, name)

missing = [i for i, _ in rows if i not in files]
if missing:
    print(f'FAIL: {len(missing)} id(s) in {CSV} have no clip in {CLIPS}: ' + ', '.join(missing), file=sys.stderr)
    sys.exit(1)
orphans = sorted(set(files) - {i for i, _ in rows})
if orphans:
    print('warning: clips with no row (ignored): ' + ', '.join(orphans), file=sys.stderr)

out = []
for i, t in rows:
    r = subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', files[i]],
                       capture_output=True, text=True)
    try:
        dur = float(r.stdout.strip())
    except ValueError:
        print(f'FAIL: ffprobe could not read {files[i]}: {r.stderr.strip()}', file=sys.stderr)
        sys.exit(1)
    out.append((i, t, round(dur, 3)))

with open(OUT_CSV, 'w', encoding='utf-8', newline='') as f:
    f.write('id,type,durSec\n')
    for i, t, d in out:
        f.write(f'{i},{t},{d:.3f}\n')

with open(OUT_TS, 'w', encoding='utf-8') as f:
    f.write('/* Generated by scripts/build_gta6_timings.py from public/gta6/voiceover/clips. Do not edit.\n'
            ' * Same rows as timings.csv. Empty array = no measured clips, timing.ts uses its constants. */\n')
    f.write('export type ClipTiming = { id: string; type: string; durSec: number };\n')
    f.write('export const clipTimings: ClipTiming[] = [\n')
    for i, t, d in out:
        f.write('  ' + json.dumps({'id': i, 'type': t, 'durSec': d}).replace('"id"', 'id').replace('"type"', 'type').replace('"durSec"', 'durSec') + ',\n')
    f.write('];\n')

print(f'ok: {len(out)} clips, total {sum(d for _, _, d in out):.1f} s -> {OUT_CSV}, {OUT_TS}')
