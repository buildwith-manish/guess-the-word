#!/usr/bin/env python3
"""Measures every NFL voiceover clip with ffprobe and writes src/nfl/timings.csv (id,type,seconds)
plus src/nfl/timings.generated.ts (the same rows as a typed module with the slot `key`, because the Remotion
bundle cannot read a CSV at runtime; src/nfl/timing.ts imports the .ts file and falls back to its constants when empty).
Pattern: scripts/build_gta6_timings.py.

Run:  python3 scripts/build_nfl_timings.py     (re-run after any change to the clips)
Env:  CSV=docs/nfl/lines.csv  CLIPS=public/nfl/voiceover/clips
Exit 1 (nothing written) if an id in lines.csv has no clip, a clip has no row, or the rows do not give the slots below.

Slot keys (the same ones scripts/build_nfl_audio_map.ts and src/nfl/timing.ts use), by walking lines.csv in order:
  hook ''  | level 'rookie' 'starter' 'hof' | scorecard 'rookie' 'starter' 'hof' (the third one closes card 30)
  cardintro '7' | clue '7.3' (card 7, clue 3) | reveal '7' | dyk '7'
  prediction '0'..'3' ('0' = intro) | rank '1'..'5' ('1' = best, Hall of Famer; the file lists the lowest first) | outro '1'..'5'
"""
import csv, json, os, subprocess, sys

CSV = os.environ.get('CSV', 'docs/nfl/lines.csv')
CLIPS = os.environ.get('CLIPS', 'public/nfl/voiceover/clips')
OUT_CSV = 'src/nfl/timings.csv'
OUT_TS = 'src/nfl/timings.generated.ts'
EXTS = ('.wav', '.mp3')
LEVELS = ['rookie', 'starter', 'hof']
TYPES = {'hook', 'level', 'cardintro', 'clue', 'reveal', 'dyk', 'scorecard', 'prediction', 'rank', 'outro'}

with open(CSV, newline='', encoding='utf-8-sig') as f:
    rows = [(r['id'].strip(), r['type'].strip()) for r in csv.DictReader(f) if r.get('id', '').strip()]

problems = []
files = {}
for name in sorted(os.listdir(CLIPS)) if os.path.isdir(CLIPS) else []:
    base, ext = os.path.splitext(name)
    if ext.lower() in EXTS:
        if base in files:
            problems.append(f'{base}: two files')
        files[base] = os.path.join(CLIPS, name)

ids = [i for i, _ in rows]
if len(set(ids)) != len(ids):
    problems.append('duplicate ids in ' + CSV)
problems += [f'{i}: in {CSV} but no clip in {CLIPS}' for i in ids if i not in files]
problems += [f'{i}: clip with no row in {CSV}' for i in sorted(set(files) - set(ids))]

# ---- slot keys: walk the rows in order ----
counts = {t: 0 for t in TYPES}
card, clue = 0, 0
keyed = []
for i, t in rows:
    if t not in TYPES:
        problems.append(f'{i}: unknown type {t!r}')
        continue
    counts[t] += 1
    k = counts[t]
    if t == 'hook':
        key = ''
    elif t == 'level':
        key = LEVELS[k - 1] if k <= 3 else ''
    elif t == 'scorecard':
        key = LEVELS[k - 1] if k <= 3 else ''
    elif t == 'cardintro':
        card, clue, key = k, 0, str(k)
    elif t == 'clue':
        clue += 1
        key = f'{card}.{clue}'
    elif t in ('reveal', 'dyk'):
        key = str(card)
    elif t == 'prediction':
        key = str(k - 1)
    elif t == 'rank':
        key = str(6 - k)
    else:  # outro
        key = str(k)
    if t == 'clue' and not (card and 1 <= clue <= 5):
        problems.append(f'{i}: clue {clue} on card {card} (a card has exactly five clues)')
    if t in ('level', 'scorecard') and not key:
        problems.append(f'{i}: more than 3 {t} rows')
    keyed.append((i, t, key))
expected = {'hook': 1, 'level': 3, 'cardintro': 30, 'clue': 150, 'reveal': 30, 'dyk': 10, 'scorecard': 3, 'prediction': 4, 'rank': 5, 'outro': 5}
for t, n in expected.items():
    if counts[t] != n:
        problems.append(f'{counts[t]} {t} rows, expected {n}')

if problems:
    print(f'FAIL ({len(problems)}):', file=sys.stderr)
    for p in problems:
        print('  ' + p, file=sys.stderr)
    sys.exit(1)

out = []
for i, t, key in keyed:
    r = subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', files[i]],
                       capture_output=True, text=True)
    try:
        dur = float(r.stdout.strip())
    except ValueError:
        print(f'FAIL: ffprobe could not read {files[i]}: {r.stderr.strip()}', file=sys.stderr)
        sys.exit(1)
    out.append((i, t, key, round(dur, 3), os.path.basename(files[i])))

with open(OUT_CSV, 'w', encoding='utf-8', newline='') as f:
    f.write('id,type,seconds\n')
    for i, t, _, d, _ in out:
        f.write(f'{i},{t},{d:.3f}\n')

with open(OUT_TS, 'w', encoding='utf-8') as f:
    f.write('/* Generated by scripts/build_nfl_timings.py from public/nfl/voiceover/clips. Do not edit by hand.\n'
            ' * Same rows as timings.csv, plus the slot `key` (src/nfl/timing.ts reads these). Empty array = no measured clips (fallback mode).\n'
            ' * One row per clip. `key` says which slot the clip belongs to:\n'
            " *   hook ''  | level 'rookie' 'starter' 'hof' | scorecard 'rookie' 'starter' 'hof' | cardintro '7' | reveal '7' | dyk '7'\n"
            " *   clue '7.3' (card 7, clue 3) | prediction '0'..'3' ('0' = intro) | rank '1'..'5' ('1' = Hall of Famer) | outro '1'..'5' */\n")
    f.write("export type ClipType = 'hook' | 'level' | 'cardintro' | 'clue' | 'reveal' | 'dyk' | 'scorecard' | 'prediction' | 'rank' | 'outro';\n")
    f.write('export type ClipTiming = { id: string; type: ClipType; key: string; durSec: number; file: string };\n')
    f.write('export const clipTimings: ClipTiming[] = [\n')
    for i, t, key, d, fn in out:
        f.write(f'  {{ id: {json.dumps(i)}, type: {json.dumps(t)}, key: {json.dumps(key)}, durSec: {d}, file: {json.dumps(fn)} }},\n')
    f.write('];\n')

print(f'ok: {len(out)} clips, total {sum(o[3] for o in out):.1f} s -> {OUT_CSV}, {OUT_TS}')
