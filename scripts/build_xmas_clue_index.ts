/**
 * Scans public/xmas/clues/ (real .png/.webp/.jpg) and public/xmas/clues/placeholders/ (.svg) and writes
 * src/xmas/clueImages.generated.ts: every clue id -> { src, isPlaceholder }. A real file always wins.
 * Prints counts of real, placeholder and missing; for real files prints the pixel size and warns when not square.
 * Run: npx tsx scripts/make_xmas_placeholders.ts && npx tsx scripts/build_xmas_clue_index.ts
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { CLUES_DIR, PLACEHOLDER_DIR, REAL_EXT, clueInfos } from './xmas_clue_ids';

const root = resolve(__dirname, '..');

/** Pixel size from the file header (png, jpg, webp). Null if unreadable. */
const sizeOf = (file: string): { w: number; h: number } | null => {
  const b = readFileSync(file);
  if (b.length > 24 && b.toString('latin1', 1, 4) === 'PNG') return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
  if (b[0] === 0xff && b[1] === 0xd8) {
    let i = 2;
    while (i + 9 < b.length) {
      if (b[i] !== 0xff) {
        i++;
        continue;
      }
      const m = b[i + 1];
      if (m >= 0xc0 && m <= 0xcf && m !== 0xc4 && m !== 0xc8 && m !== 0xcc) return { h: b.readUInt16BE(i + 5), w: b.readUInt16BE(i + 7) };
      i += 2 + b.readUInt16BE(i + 2);
    }
    return null;
  }
  if (b.length > 30 && b.toString('latin1', 0, 4) === 'RIFF' && b.toString('latin1', 8, 12) === 'WEBP') {
    const k = b.toString('latin1', 12, 16);
    if (k === 'VP8X') return { w: 1 + b.readUIntLE(24, 3), h: 1 + b.readUIntLE(27, 3) };
    if (k === 'VP8L') {
      const v = b.readUInt32LE(21);
      return { w: (v & 0x3fff) + 1, h: ((v >> 14) & 0x3fff) + 1 };
    }
    if (k === 'VP8 ') return { w: b.readUInt16LE(26) & 0x3fff, h: b.readUInt16LE(28) & 0x3fff };
  }
  return null;
};

type Entry = { src: string; isPlaceholder: boolean };
const entries: Record<string, Entry> = {};
let real = 0;
let placeholder = 0;
const missing: string[] = [];
const warnings: string[] = [];
const multi: string[] = [];

for (const { id } of clueInfos()) {
  const found = REAL_EXT.filter((e) => existsSync(join(root, CLUES_DIR, id + e)));
  if (found.length > 1) multi.push(`${id}: ${found.join(', ')} (using ${found[0]})`);
  if (found.length) {
    const file = join(root, CLUES_DIR, id + found[0]);
    entries[id] = { src: `xmas/clues/${id}${found[0]}`, isPlaceholder: false };
    real++;
    const s = sizeOf(file);
    if (!s) console.log(`  real ${id}${found[0]}: size unreadable`);
    else {
      console.log(`  real ${id}${found[0]}: ${s.w}x${s.h}`);
      if (s.w !== s.h) warnings.push(`${id}: not square (${s.w}x${s.h})`);
    }
  } else if (existsSync(join(root, PLACEHOLDER_DIR, id + '.svg'))) {
    entries[id] = { src: `xmas/clues/placeholders/${id}.svg`, isPlaceholder: true };
    placeholder++;
  } else missing.push(id);
}

const body = Object.entries(entries)
  .map(([id, e]) => `  ${JSON.stringify(id)}: { src: ${JSON.stringify(e.src)}, isPlaceholder: ${e.isPlaceholder} },`)
  .join('\n');
writeFileSync(
  join(root, 'src/xmas/clueImages.generated.ts'),
  `// GENERATED by scripts/build_xmas_clue_index.ts. Do not edit.\n// src is relative to public/ (use staticFile). A real file always wins over a placeholder.\nexport type ClueImageEntry = { src: string; isPlaceholder: boolean };\n\nexport const clueImages: Record<string, ClueImageEntry> = {\n${body}\n};\n`,
);

multi.forEach((m) => console.warn(`WARN two real files: ${m}`));
warnings.forEach((w) => console.warn(`WARN ${w}`));
console.log(`real: ${real}, placeholder: ${placeholder}, missing: ${missing.length}`);
if (missing.length) {
  console.error(`MISSING (run make_xmas_placeholders.ts first): ${missing.join(', ')}`);
  process.exitCode = 1;
}
