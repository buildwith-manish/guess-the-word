#!/usr/bin/env python3
"""Measures every Don't Say The Same As Me voiceover clip with ffprobe and writes src/dontsay/timings.csv
(id,type,durSec) plus src/dontsay/timings.generated.ts (the same rows as a typed module, because the Remotion
bundle cannot read a CSV at runtime; src/dontsay/timing.ts imports the .ts file and uses its base constants for
any clip that is not in it). Pattern (idea only): scripts/build_gta6_timings.py.

Run:   python3 scripts/build_dontsay_timings.py     (re-run after any change to the clips, e.g. clean_dontsay_clips.sh)
Env:   CSV=docs/dontsay/lines.csv  CLIPS=public/dontsay/voiceover/clips
       OUT_CSV=src/dontsay/timings.csv  OUT_TS=src/dontsay/timings.generated.ts   (to write somewhere else)
       PARTIAL=1   write only the clips that exist (voice arrives in batches); the rest keep their base timing.
Exit 1 if any id in lines.csv has no clip (nothing is written then, unless PARTIAL=1). Clips with no row are
reported and ignored. Ids with the same name but two extensions are an error."""
import csv, json, os, subprocess, sys

CSV = os.environ.get('CSV', 'docs/dontsay/lines.csv')
CLIPS = os.environ.get('CLIPS', 'public/dontsay/voiceover/clips')
OUT_CSV = os.environ.get('OUT_CSV', 'src/dontsay/timings.csv')
OUT_TS = os.environ.get('OUT_TS', 'src/dontsay/timings.generated.ts')
PARTIAL = os.environ.get('PARTIAL', '0') == '1'
EXTS = ('.wav', '.mp3', '.m4a', '.flac', '.ogg')

with open(CSV, newline='', encoding='utf-8') as f:
    rows = [(r['id'].strip(), r['type'].strip()) for r in csv.DictReader(f) if (r.get('id') or '').strip()]

ids = [i for i, _ in rows]
if len(set(ids)) != len(ids):
    dup = sorted({i for i in ids if ids.count(i) > 1})
    print(f'FAIL: duplicate ids in {CSV}: ' + ', '.join(dup), file=sys.stderr)
    sys.exit(1)

files = {}
for name in sorted(os.listdir(CLIPS)) if os.path.isdir(CLIPS) else []:
    base, ext = os.path.splitext(name)
    if ext.lower() in EXTS:
        if base in files:
            print(f'FAIL: {base} exists with two extensions in {CLIPS}', file=sys.stderr)
            sys.exit(1)
        files[base] = os.path.join(CLIPS, name)

missing = [i for i in ids if i not in files]
if missing and not PARTIAL:
    print(f'FAIL: {len(missing)} id(s) in {CSV} have no clip in {CLIPS}: ' + ', '.join(missing), file=sys.stderr)
    print('      (PARTIAL=1 writes only the clips that exist)', file=sys.stderr)
    sys.exit(1)
if missing:
    print(f'note: PARTIAL=1, {len(missing)} of {len(ids)} ids have no clip yet; they keep their base timing', file=sys.stderr)
orphans = sorted(set(files) - set(ids))
if orphans:
    print('warning: clips with no row (ignored): ' + ', '.join(orphans), file=sys.stderr)

out = []
for i, t in rows:
    if i not in files:
        continue
    r = subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', files[i]],
                       capture_output=True, text=True)
    try:
        dur = float(r.stdout.strip())
    except ValueError:
        print(f'FAIL: ffprobe could not read {files[i]}: {r.stderr.strip()}', file=sys.stderr)
        sys.exit(1)
    out.append((i, t, round(dur, 3), os.path.basename(files[i])))

for path in (OUT_CSV, OUT_TS):
    os.makedirs(os.path.dirname(path) or '.', exist_ok=True)

with open(OUT_CSV, 'w', encoding='utf-8', newline='') as f:
    f.write('id,type,durSec\n')
    for i, t, d, _ in out:
        f.write(f'{i},{t},{d:.3f}\n')

with open(OUT_TS, 'w', encoding='utf-8') as f:
    f.write('/* Generated by scripts/build_dontsay_timings.py from public/dontsay/voiceover/clips. Do not edit.\n'
            ' * Same rows as timings.csv. A clip that is not listed keeps its base timing in timing.ts (empty array = no clips yet). */\n')
    f.write('export type ClipTiming = { id: string; type: string; durSec: number; file: string };\n')
    f.write('export const clipTimings: ClipTiming[] = [\n')
    for i, t, d, fn in out:
        f.write(f'  {{ id: {json.dumps(i)}, type: {json.dumps(t)}, durSec: {d}, file: {json.dumps(fn)} }},\n')
    f.write('];\n')

print(f'ok: {len(out)} of {len(ids)} clips, total {sum(o[2] for o in out):.1f} s -> {OUT_CSV}, {OUT_TS}')
