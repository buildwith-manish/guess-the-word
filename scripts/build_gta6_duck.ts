/**
 * Bakes the music ducking envelope of GTA6-Full from the voice clip timeline (src/gta6/voiceTimeline.ts).
 * Run: npx tsx scripts/build_gta6_duck.ts     (re-run after any change to clips, timing or parts)
 * Writes src/gta6/duckEnvelope.generated.ts: keyframes [render frame, gain 0..1], linear between them.
 * Gain is 1 with no voice and MIX.musicDuck while a clip plays; ramps MIX.duckAttackSec before a clip and
 * MIX.duckReleaseSec after it; clips closer than attack + release share one dip.
 * Also prints voice/voice overlaps and SFX moved off a voice start.
 */
import { writeFileSync } from 'node:fs';
import { MIX, sfxEvents, totalFrames, voiceEvents, voiceOverlaps, voiceSignature } from '../src/gta6/voiceTimeline';
import { RENDER_FPS, ticksToFrames, timecode, ticksToSec } from '../src/gta6/timing';

const att = Math.round(MIX.duckAttackSec * RENDER_FPS);
const rel = Math.round(MIX.duckReleaseSec * RENDER_FPS);

const spans = voiceEvents
  .map((e) => {
    const a = ticksToFrames(e.tick);
    const len = Math.ceil(e.sec * RENDER_FPS);
    return [a, Math.min(a + len, ticksToFrames(e.endTick))] as [number, number];
  })
  .sort((x, y) => x[0] - y[0]);

const merged: [number, number][] = [];
for (const s of spans) {
  const last = merged[merged.length - 1];
  if (last && s[0] - last[1] < att + rel) last[1] = Math.max(last[1], s[1]);
  else merged.push([s[0], s[1]]);
}

const keys: [number, number][] = [[0, 1]];
const push = (f: number, g: number) => {
  const prev = keys[keys.length - 1];
  keys.push([Math.max(f, prev[0] + (f <= prev[0] ? 1 : 0)), g]);
};
for (const [a, b] of merged) {
  push(Math.max(0, a - att), 1);
  push(a, MIX.musicDuck);
  push(b, MIX.musicDuck);
  push(b + rel, 1);
}
push(totalFrames, 1);

const out = `/* Generated by scripts/build_gta6_duck.ts from src/gta6/voiceTimeline.ts. Do not edit. */
/** Fingerprint of the voice timeline this envelope was baked from (Audio.tsx throws when it no longer matches). */
export const DUCK_SIGNATURE = '${voiceSignature()}';
/** [render frame of GTA6-Full, music gain multiplier 0..1], linear between keys. */
export const DUCK_KEYS: readonly (readonly [number, number])[] = ${JSON.stringify(keys)};
`;
writeFileSync('src/gta6/duckEnvelope.generated.ts', out);

console.log(`voice clips ${voiceEvents.length}, dips ${merged.length}, keys ${keys.length}, signature ${voiceSignature()}`);
const tc = (t: number) => `${timecode(ticksToSec(t))}.${String(Math.round((ticksToSec(t) % 1) * 100)).padStart(2, '0')}`;
console.log(`\nvoice/voice overlaps: ${voiceOverlaps.length}`);
for (const o of voiceOverlaps) console.log(`  ${tc(o.b.tick)}  ${o.a.id} (${o.a.what}) still playing ${o.overlapSec.toFixed(2)} s when ${o.b.id} (${o.b.what}) starts`);
const moved = sfxEvents.filter((s) => s.nudgedFrom !== undefined);
console.log(`\nsfx moved off a voice start: ${moved.length}`);
for (const s of moved) console.log(`  ${s.cue.sfx} ${tc(s.nudgedFrom!)} -> ${tc(s.tick)} (voice ${s.collidedWith!.id}, ${s.collidedWith!.what})`);
